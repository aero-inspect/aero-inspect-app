// Offline generator: derive SQL from the shared scene, never from screenshot coordinates.
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try {
    const page=await browser.newPage();
    await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
    const result=await page.evaluate(async()=>{const {generateInspectionPlans}=await import('/src/components/bragado/inspectionPlans.ts');return generateInspectionPlans();});
    const quote=s=>"'"+s.replaceAll("'","''")+"'";
    const rows=result.plans.map(p=>`(${quote(p.code)}, ${quote(p.type)}, ${quote(JSON.stringify(p.route))}::jsonb)`).join(',\n');
    const sql=`-- Generated by aero-inspect-app/scripts/generate-inspection-seed.cjs.
-- Model clearance ${result.clearance}m; heights and georeference remain estimated, not flight-certified.
-- Loaded after data.sql and bragado-assets.sql. Existing sample plans remain untouched.
WITH guard AS MATERIALIZED (SELECT pg_advisory_xact_lock(198411, 310)),
seed(code, type, route) AS (VALUES
${rows}
),
catalog AS MATERIALIZED (
  SELECT a.id_asset, s.*, 'Inspeccion 3D - ' || s.code AS plan_name
  FROM seed s JOIN asset a ON a.code = s.code AND a.type = s.type CROSS JOIN guard
),
new_plans AS (
  INSERT INTO flight_plan(name, objective, cruise_speed_ms, min_battery_pct, status)
  SELECT c.plan_name, 'Inspeccion completa reutilizable de ' || c.code, 2.0, 30, 'CONFIRMED'
  FROM catalog c WHERE NOT EXISTS (SELECT 1 FROM flight_plan f WHERE f.name = c.plan_name)
  RETURNING id_flight_plan, name
),
plans AS MATERIALIZED (
  SELECT c.*, f.id_flight_plan FROM catalog c JOIN new_plans f ON f.name = c.plan_name
  UNION ALL
  SELECT c.*, f.id_flight_plan FROM catalog c JOIN flight_plan f ON f.name = c.plan_name
),
associations AS (
  INSERT INTO flight_plan_asset(id_flight_plan, asset_ids)
  SELECT p.id_flight_plan, p.id_asset FROM plans p
  WHERE NOT EXISTS (SELECT 1 FROM flight_plan_asset a WHERE a.id_flight_plan = p.id_flight_plan AND a.asset_ids = p.id_asset)
  RETURNING id_flight_plan
),
route AS MATERIALIZED (
  SELECT p.id_flight_plan, p.id_asset, w.* FROM plans p,
  jsonb_to_recordset(p.route) AS w(latitude double precision, longitude double precision, altitude double precision, sequence integer, action text, "pointOfInterest" boolean, "stopSeconds" double precision, "droneDegree" double precision, pitch double precision)
),
new_waypoints AS (
  INSERT INTO plan_waypoint(id_flight_plan, latitude, longitude, altitude, sequence, stop_seconds, point_of_interest, action, drone_degree, id_asset, name, description)
  SELECT r.id_flight_plan,r.latitude,r.longitude,r.altitude,r.sequence,r."stopSeconds",r."pointOfInterest",r.action,r."droneDegree",
    CASE WHEN r."pointOfInterest" THEN r.id_asset END,
    CASE WHEN r."pointOfInterest" THEN 'Inspeccion ' || r.sequence END, NULL
  FROM route r WHERE NOT EXISTS(SELECT 1 FROM plan_waypoint w WHERE w.id_flight_plan=r.id_flight_plan AND w.sequence=r.sequence)
  ORDER BY r.id_flight_plan,r.sequence
  RETURNING id_plan_waypoint,id_flight_plan,sequence
),
waypoints AS (
  SELECT * FROM new_waypoints
  UNION ALL
  SELECT w.id_plan_waypoint,w.id_flight_plan,w.sequence FROM plan_waypoint w JOIN plans p ON p.id_flight_plan=w.id_flight_plan
)
INSERT INTO plan_waypoint_camera_angle(id_plan_waypoint,pitch,yaw)
SELECT w.id_plan_waypoint,r.pitch,0.0 FROM waypoints w JOIN route r USING(id_flight_plan,sequence)
WHERE r."pointOfInterest" AND NOT EXISTS(SELECT 1 FROM plan_waypoint_camera_angle a WHERE a.id_plan_waypoint=w.id_plan_waypoint);
`;
    const target=path.resolve(__dirname,'../../general-monolith/src/main/resources/database.script/bragado-inspection-plans.sql');
    fs.writeFileSync(target,sql);
    fs.writeFileSync(path.resolve(__dirname,'../docs/inspection-plan-validation.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify({plans:result.plans.length,bounds:result.bounds,cruise:result.cruise,reports:result.reports},null,2));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
