const assert=require('node:assert/strict');
const {buildSync}=require('esbuild');
const Module=require('node:module');
const path=require('node:path');
const T=require('three');
function load(file){const output=buildSync({entryPoints:[file],bundle:true,platform:'node',format:'cjs',external:['three'],write:false}).outputFiles[0].text;const compiled=new Module(path.resolve(file),module);compiled.paths=module.paths;compiled._compile(output,path.resolve(file));return compiled.exports;}
const {createMissionPlayback}=load('frontend/src/components/bragado/missionPlayback.ts');
const {LUJAN_DRONE_BASE:base,LUJAN_DRONE_SCALE:scale,lujanPlaybackReference:reference}=load('frontend/src/components/lujan/drone.ts');
const {lujanToGeographic,isInsideLujan}=load('frontend/src/data/plants.ts');
const storage=new Map();global.sessionStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
const scene=new T.Scene(),camera=new T.PerspectiveCamera(),controls={target:new T.Vector3()};
const dock=new T.Group(),drone=new T.Group();drone.name='Reference quadcopter';drone.position.y=.113;dock.add(drone);scene.add(dock);
dock.scale.setScalar(scale);
const home=reference.toPosition({...base,altitude:0});dock.position.set(home.x,0,home.z);
assert.ok(isInsideLujan(home.x,home.z));
const gps=lujanToGeographic(home.x,home.z);assert.ok(Math.abs(gps.latitude-base.latitude)<1e-10&&Math.abs(gps.longitude-base.longitude)<1e-10);
assert.equal(reference.toPosition({...base,absoluteAltitude:100}),null,'Unknown absolute altitude must not be treated as relative altitude');
const play=createMissionPlayback(scene,dock,camera,controls,reference);
const points=[{...base,altitude:5,sequence:0},{latitude:base.latitude+.00005,longitude:base.longitude+.00005,altitude:8,sequence:1}];
const data={id:'qa-lujan',status:'PLANNED',points,telemetry:null};play.update(data);
assert.ok(drone.position.distanceTo(home)<1e-8,'Planned mission leaves drone on the dock');
const planned=scene.getObjectByName('Planned mission route');assert.equal(planned.geometry.attributes.position.count,2);
assert.ok(Math.abs(planned.geometry.attributes.position.getY(1)-(8+reference.groundHeight))<1e-5);
data.status='IN_PROGRESS';play.update(data);assert.ok(drone.position.distanceTo(home)<1e-8,'No invented flight without telemetry');
const sample=(seconds,point)=>({missionId:data.id,timestamp:new Date(1700000000000+seconds*1000).toISOString(),position:{...point,relativeAltitude:point.altitude,absoluteAltitude:100},velocity:{headingDegree:90}});
data.telemetry=sample(1,points[0]);play.update(data);play.animate(performance.now()+1000);
assert.ok(drone.position.distanceTo(reference.toPosition(points[0]))<1e-8);
data.telemetry=sample(2,points[1]);play.update(data);play.animate(performance.now()+1000);
assert.ok(drone.position.distanceTo(reference.toPosition(points[1]))<1e-8);
assert.ok(Math.abs(drone.rotation.y+Math.PI/2)<1e-8,'Heading uses geographic north');
assert.equal(scene.getObjectByName('Actual mission trail').geometry.attributes.position.count,2);
data.telemetry=sample(1,points[0]);play.update(data);play.animate(performance.now()+1000);
assert.ok(drone.position.distanceTo(reference.toPosition(points[1]))<1e-8,'Stale telemetry ignored');
play.setFollowing(true);play.animate(performance.now()+1100);assert.ok(controls.target.length()>0);
data.status='COMPLETED';play.update(data);data.telemetry=sample(3,points[0]);play.update(data);play.animate(performance.now()+2000);
assert.ok(drone.position.distanceTo(reference.toPosition(points[1]))<1e-8,'Completed mission freezes');
play.destroy();assert.equal(scene.getObjectByName('Planned mission route'),undefined);
const {plantGeoreference:g,toPlantPosition}=load('frontend/src/components/bragado/georeference.ts');
const bragadoScene=new T.Scene(),bragadoDock=new T.Group(),bragadoDrone=new T.Group();
bragadoDrone.name='Reference quadcopter';bragadoDrone.position.y=.113;bragadoDock.position.set(-72,0,-65);bragadoDock.add(bragadoDrone);bragadoScene.add(bragadoDock);
const bragadoPlay=createMissionPlayback(bragadoScene,bragadoDock,camera,controls);
const bragadoPoint={latitude:g.latitude,longitude:g.longitude,altitude:10,sequence:0};
bragadoPlay.update({id:'qa-bragado',status:'PLANNED',points:[bragadoPoint],telemetry:null});
assert.equal(bragadoDrone.position.y,g.groundHeight);
bragadoPlay.update({id:'qa-bragado',status:'IN_PROGRESS',points:[bragadoPoint],telemetry:{...sample(4,bragadoPoint),missionId:'qa-bragado'}});
bragadoPlay.animate(performance.now()+1000);
assert.ok(bragadoDrone.position.distanceTo(toPlantPosition(bragadoPoint))<1e-8,'Existing Bragado projection is preserved');
bragadoPlay.destroy();
console.log('Luján: dock GPS, altitude, planned route, telemetry flight, actual trail, heading, stale packets, follow and completion passed.');
